import 'dart:math';

class Solution {
  int minimumSumSubarray(List<int> nums, int l, int r) {
    int res = 9223372036854775807;
    for (var i = 0; i < nums.length; i++) {
      int current = 0, counter = 0;
      for (var j = i; j < nums.length; j++) {
        counter++;
        current += nums[j];
        if (counter < l) continue;
        if (counter > r) continue;
        if (current > 0) res = min(res, current);
      }
    }
    return res == 9223372036854775807 ? -1 : res;
  }
}

